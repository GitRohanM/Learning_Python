#Arithmetic Operators
a = 10
b = 3
print("Addition:",a+b)
print("Subtraction:",a-b)
print("Multiplication:",a*b)
print("Division:",a/b)
print("Modulus:",a%b)
print("Exponentiation:",a**b)

#Relational/Comparison Operators
num1 = 20
num2 = 10
print(num1 == num2)
print(num1 != num2)
print(num1 > num2)
print(num1 >= num2)
print(num1 < num2)
print(num1 <= num2)

#Assignment Operators
num = 50  # =
print("Num:", num)
num += 1  # +=
print("Num:", num)
num -= 1 # -=
print("Num:", num)
num *= 1  # *=
print("Num:", num)
num /= 1 # /=
print("Num:", num)

#Logical Operators
a = 50
b = 30
print(not(a > b))  # not

val1 = True
val2 = True
print("And operator:", val1 and val2)  # and

val1 = False
val2 = False
print ("Or operator:", val1 or val2)  # or
